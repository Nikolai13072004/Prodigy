import { deflateRawSync } from "zlib";

type CellValue = string | number | null | undefined;

type ZipEntry = {
  name: string;
  data: Buffer;
};

const CRC32_TABLE = new Uint32Array(256).map((_, index) => {
  let crc = index;
  for (let bit = 0; bit < 8; bit += 1) {
    crc = (crc & 1) !== 0 ? 0xedb88320 ^ (crc >>> 1) : crc >>> 1;
  }
  return crc >>> 0;
});

